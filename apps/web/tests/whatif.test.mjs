// What-if display and free-text routing on the demo page. Fixtures are outputs of Max's
// heatcheck.agents.scenario on the committed forecast (see the fixture's _provenance).
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import * as S from "../web/whatif/whatif.js";

const here = dirname(fileURLToPath(import.meta.url));
const F = JSON.parse(readFileSync(join(here, "fixtures", "whatif", "whatif_cases.json"), "utf8"));
const C = F.cases;

test("fixture is generated by Max's code, not hand-written", () => {
  assert.match(F._provenance, /^Generated by heatcheck\.agents\.scenario/);
});

test("route and scenario calls use relative URLs only, and a down router falls back to the dialogue", async () => {
  const seen = [];
  const fetchImpl = async (url, init) => {
    seen.push(url);
    return { ok: true, status: 200, json: async () => ({ action: "OPEN_BOARD", reason: "x", heater_text: "hi" }) };
  };
  const r = await S.routeMessage("find me a market", { fetchImpl });
  assert.equal(r.action, "OPEN_BOARD");
  assert.deepEqual(seen, ["/api/route"]);
  for (const u of [S.ROUTE_URL, S.SCENARIO_URL, S.ESTIMATE_URL]) assert.ok(u.startsWith("/api/"));
  const down = await S.routeMessage("x", { fetchImpl: async () => { throw new Error("down"); } });
  assert.equal(down.action, "DIALOGUE");
  const odd = await S.routeMessage("x", { fetchImpl: async () => ({ ok: true, status: 200, json: async () => ({ action: "BET" }) }) });
  assert.equal(odd.action, "DIALOGUE");
});

test("confirmation echoes exactly what the server showed", () => {
  const it = C.neutral.interpretation;
  assert.deepEqual(S.confirmBody(it), { game_id: it.game_id, changes: it.changes, focus_team: it.focus_team,
    interpretation_id: it.interpretation_id, confirmed: true, message_sha256: it.message_sha256 });
  assert.ok(!/\d+(\.\d+)?%/.test(it.heater_text), "the interpretation shows no number");
});

test("neutral floor: baseline vs scenario side by side, HYPOTHETICAL, model recalculated", () => {
  const v = S.scenarioView(C.neutral.estimate);
  assert.equal(v.badge, "HYPOTHETICAL");
  assert.equal(v.baseline, "73.3%");   // Boston at Milwaukee: no home court for Milwaukee
  assert.equal(v.scenario, "83.0%");
  assert.equal(v.effects[0].label, "MODEL RECALCULATED");
  assert.equal(v.verdict, "HYPOTHETICAL · Edge unverified");
});

test("your own adjustment is labelled as yours", () => {
  const v = S.scenarioView(C.assume_pp.estimate);
  assert.equal(v.effects[0].label, "YOUR ASSUMPTION");
  assert.match(v.effects[0].text, /^Your assumption, not modelled/);
  assert.equal(v.baseline, "73.3%");   // Boston are the away team at Milwaukee
  assert.equal(v.scenario, "68.3%");
});

test("game points without a conversion, and a player with no estimate, give no number", () => {
  for (const k of ["points", "no_data"]) {
    const v = S.scenarioView(C[k].estimate);
    assert.equal(v.scenario, "No number");
    assert.equal(v.effects[0].label, "NO NUMBER");
  }
  assert.match(S.scenarioView(C.no_data.estimate).effects[0].text, /No data/);
});

test("player out uses Research's shrunk estimate, labelled ESTIMATE, with a range and n", () => {
  const v = S.scenarioView(C.player_out.estimate);
  assert.equal(v.effects[0].label, "ESTIMATE");
  assert.equal(v.baseline, "67.6%");
  assert.equal(v.scenario, "67.6% (range 57.5% to 76.3%)");
  assert.ok(!/raw/i.test(JSON.stringify(v.effects.map((e) => e.label))));
});

test("a hypothetical price leaves the forecast unchanged and says so", () => {
  const v = S.scenarioView(C.price.estimate);
  assert.equal(v.scenario, "32.4% (forecast unchanged)");
  assert.equal(v.price, "Hypothetical market price: 30.0%");
});

test("a SAMPLE estimate never shows a number", () => {
  const est = { ...C.neutral.estimate, is_sample: true, baseline: null, scenario: null };
  const v = S.scenarioView(est);
  assert.equal(v.badge, "SAMPLE");
  assert.equal(v.baseline, "SAMPLE: not shown");
  assert.equal(v.scenario, "No number");
});

test("no view text calls anything an edge found or a bet", () => {
  for (const c of Object.values(C)) {
    const v = S.scenarioView(c.estimate);
    const all = JSON.stringify(v) + c.estimate.ref_text;
    assert.ok(!/\bbet\b|edge found|guarantee/i.test(all), all);
    assert.ok(c.estimate.ref_text.startsWith("HYPOTHETICAL · Edge unverified"));
  }
});
